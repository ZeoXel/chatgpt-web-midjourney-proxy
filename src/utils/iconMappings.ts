// 获取对应的图标组件
export const getIconComponent = (iconName?: string) => {
  if (!iconName) return null

  // 优先使用映射表
  if (iconMappings[iconName]) {
    return iconMappings[iconName]
  }

  // 如果是 ionicons5 格式的图标名，直接使用
  if (iconName.startsWith('ion:')) {
    const cleanName = iconName.replace('ion:', '')
    return ionicons5[cleanName as keyof typeof ionicons5] || ionicons5.HelpOutline
  }

  // 如果是直接的 ionicons5 图标名
  if (iconName in ionicons5) {
    return ionicons5[iconName as keyof typeof ionicons5]
  }

  // 兜底使用原来的 iconify 图标
  return null
}

// 标准化图标尺寸映射
export const sizeMapping: Record<string, string> = {
  'xs': '12px',
  'sm': '16px',
  'md': '20px',
  'lg': '24px',
  'xl': '28px',
  '2xl': '32px',
  '3xl': '36px',
  '4xl': '40px',
  '5xl': '48px',
  '6xl': '56px',
}

// 获取标准化尺寸
export const getStandardSize = (size?: string | number): string => {
  if (!size) return '1em'

  if (typeof size === 'number') {
    return `${size}px`
  }

  if (sizeMapping[size]) {
    return sizeMapping[size]
  }

  return size
}